public class Main {
    public static void main(String[] args) {
        int n = 5;

        System.out.println("1 sampai N:");
        for (int i = 1; i <= n; i++) {
            System.out.println(i);
        }

        System.out.println("N sampai 1:");
        for (int i = n; i >= 1; i--) {
            System.out.println(i);
        }
    }
}
